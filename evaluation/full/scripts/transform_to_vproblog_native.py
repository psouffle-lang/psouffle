@dataclass
class TransformResult:
    rules_text: str
    edb_conf_text: str
    metadata: Dict[str, object]


def classify_predicates(
    rules: Sequence[Rule], edb_names: Sequence[str]
) -> Tuple[Set[str], Set[str]]:
    """Return (edb_predicates, idb_predicates).

    An EDB predicate is one present in the edb.conf file (`esrc_*` in our
    benchmark). All predicates that appear as a rule head become IDB; body
    atoms that match neither set are treated as IDB references (consistent
    with vlog's open-world view).
    """
    edb = set(edb_names)
    idb: Set[str] = set()
    for r in rules:
        idb.add(r.head_pred)
    # Predicates appearing only in body and not in EDB/IDB — treat as IDB
    # (they'll just never populate anything, consistent with the bridge form).
    for r in rules:
        for b in r.body:
            if b.is_atom and b.pred is not None:
                if b.pred not in edb:
                    idb.add(b.pred)
    return edb, idb


def render_args(args: Sequence[str]) -> str:
    return ", ".join(args)


def fresh_var(base: str, index: int) -> str:
    return f"{base}{index}"


_EQ_CONSTRAINT_RE = re.compile(
    r"^\s*(~?)\s*\(+\s*([A-Z][A-Za-z0-9_]*)\s*=\s*([0-9]+)\s*\)+\s*$"
)
# Accept bare Souffle-style `i != 0` and `i == 0` (no parens, any identifier
# case). Captures: (operator, var, const). Routed to vlog's NE/EQCMP builtin
# via `_constraint_to_vlog_text`.
_NEQ_CONSTRAINT_RE = re.compile(
    r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*(!=|==)\s*([0-9]+)\s*$"
)


_DECR_CONSTRAINT_RE = re.compile(
    r"^\s*\(\s*([A-Z_][A-Za-z0-9_]*)\s*=\s*\(\s*([A-Z_][A-Za-z0-9_]*)\s*-\s*1\s*\)\s*\)\s*$"
)
_BAND_CONSTRAINT_RE = re.compile(
    r"^\s*\(\s*([A-Z_][A-Za-z0-9_]*)\s*=\s*\(\s*([A-Z_][A-Za-z0-9_]*)\s+band\s+([A-Z_][A-Za-z0-9_]*)\s*\)\s*\)\s*$"
)
# Native SUM aggregate produced by `sum_aggregate_rewrite.py --mode native`
# (or hand-written in a TcP-native form): `V = sum(W, pred(args...))`.
# Captures: (lhs_var, value_var, inner_pred_text). The inner predicate
# text is parsed by `_parse_atom_args` below so TcP column lifting (F + I
# for IDB, F-only for EDB) can be applied inside the sum.
_SUM_AGG_BODY_RE = re.compile(
    r"^\s*([A-Z_][A-Za-z0-9_]*)\s*=\s*sum\s*\(\s*([A-Z_][A-Za-z0-9_]*)\s*,\s*(.+)\s*\)\s*$",
    re.DOTALL,
)
_ATOM_HEAD_RE = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*\((.*)\)\s*$", re.DOTALL)

_VAR_NAME_RE = re.compile(r"^[A-Z_][A-Za-z0-9_]*$")


def _is_variable(token: str) -> bool:
    """vlog treats identifiers starting with uppercase or `_` as variables."""
    return bool(_VAR_NAME_RE.match(token))


def _constraint_to_vlog_text(raw: str) -> Optional[str]:
    """Render a Souffle-style body constraint into vlog's BuiltinConstraint
    surface syntax (no parens, no leading `~` — negation is encoded by
    flipping the operator). Returns None if the form isn't recognised so
    the caller can fall back to verbatim emission.

    vlog's `tryParseBuiltinConstraint` rejects items containing parens, so
    every Souffle wrapping `(X = 0)` / `~((X = 0))` / `(TIMES_NEW = (TIMES
    - 1))` / `(TMP = (X band Y))` is unwrapped here. The emitted text
    passes through vlog's parser, which recognises `<`, `<=`, `>`, `>=`,
    `=`, `==`, `!=` and binary operators `+ - * / %` plus the Souffle
    bitwise keyword `band` (engine maps `band` to `BuiltinOp::BAND` via the
    keyword normaliser inserted before whitespace-stripping in
    `tryParseBuiltinConstraint`). Comparisons and arith-assignments land
    in `Rule::builtins` and fire from `SemiNaiver::applyBuiltinsAndEmitHead`
    — the same path that already knows how to project conj(F0,...,Fn)
    function-term head positions through chaseMgmt.
    """
    s = raw.strip()
    # `(X = c)` (positive equality) → `X = c`; `~((X = c))` → `X != c`.
    m = _EQ_CONSTRAINT_RE.match(s)
    if m is not None:
        negated, var, const = m.group(1), m.group(2), m.group(3)
        op = "!=" if negated else "="
        return f"{var} {op} {const}"
    # Bare Souffle `i != 0` / `i == 0`.
    m = _NEQ_CONSTRAINT_RE.match(s)
    if m is not None:
        var, op, const = m.group(1), m.group(2), m.group(3)
        return f"{var} {op} {const}"
    # `(TIMES_NEW = (TIMES - 1))` → `TIMES_NEW = TIMES - 1`. vlog's parser
    # has a `<var> = <expr>` special case that lifts the RHS into a SUB
    # builtin and binds TIMES_NEW to its result, so this works as a binding
    # constraint not just a filter.
    m = _DECR_CONSTRAINT_RE.match(s)
    if m is not None:
        v_new, v_src = m.group(1), m.group(2)
        return f"{v_new} = {v_src} - 1"
    # `(TMP = (X band Y))` → `TMP = X band Y`. Parser maps the `band`
    # keyword to `BuiltinOp::BAND`, and the `<var> = <expr>` fast path
    # binds TMP directly (same shape as the SUB-binding for decrement).
    m = _BAND_CONSTRAINT_RE.match(s)
    if m is not None:
        tmp, x, y = m.group(1), m.group(2), m.group(3)
        return f"{tmp} = {x} band {y}"
    return None


def build_t_rule(
    rule: Rule, rule_index: int, edb: Set[str], idb: Set[str],
    naf_idb_used: Optional[Set[str]] = None,
    head_const_consts: Optional[Set[str]] = None,
) -> Tuple[Optional[str], List[str], str]:
    """Return the rendered t_<N>_<head>(...) :- body. rule and the list of
    probabilistic body-formula variable names it introduced. Returns
    (None, []) if the rule's constraints are jointly unsatisfiable — the
    caller should drop such rules (they never fire in Souffle either).

    NAF on an IDB predicate is rewritten as `~has_<pred>(keys...)`: the
    caller must emit the `has_<pred>(keys...) :- <pred>(keys..., F, I),
    ~d_<pred>(I).` witness rule once per predicate recorded in
    `naf_idb_used`. Without this rewrite, vlog's left-join processor
    SIGSEGVs at InterTableJoinProcessor::processResults when a negated
    body atom introduces fresh F/I vars that aren't bound by a preceding
    positive literal (as happens for e.g. pt-obj-dlog's
    `!staticM(m)` → `~staticM(M,F1,I1), ~d_staticM(I1)`).

    Constants in the rule head are lifted into a synthetic body atom
    `esrc_ctx_<const>(V)` and replaced by a fresh variable `V`: vlog's
    ExistentialRuleProcessor indexes `posFuncArgColumns` by head-tuple
    position but the row passed to ChaseMgmt::Rows::addRow is built from
    `colsForExt` (which skips constant positions), so a literal constant
    shifts the F-column indices and addRow reads past the row end → "null
    formula" error. Observed on pt-obj-dlog rule t_85_reachableCM(0, M,
    F0, F1, conj(F0, F1)). The caller must materialise an EDB file
    `data/esrc_ctx_<const>.csv` with a single row (the constant) for each
    constant recorded in `head_const_consts`.
    """
    f_vars: List[str] = []          # F_i variables, one per probabilistic body atom
    new_body_parts: List[str] = []
    # Every Souffle constraint — positive `(X = C)`, negated `~((X = C))`,
    # bare `X != C`, arith decrement `(V_NEW = (V - 1))`, bitwise
    # `(TMP = (X band Y))` — is routed to vlog's BuiltinConstraint engine
    # by `_constraint_to_vlog_text` below. No Python-side substitution or
    # EDB-split rewriting happens any more; the engine handles the
    # semantics.

    # Translatability check: head variables must be bound by either
    #   (a) a positive body atom argument,
    #   (b) a positive `(X = C)` constraint — vlog's `tryParseBuiltinConstraint`
    #       routes this through EQCMP, which acts as a filter binding X to C
    #       for any row where that atom-bound X already equals C,
    #   (c) a `<var> = <expr>` arithmetic or bitwise builtin that vlog's
    #       parser lifts into a binding form (covers `TIMES_NEW = TIMES - 1`,
    #       `TMP = X band Y`, etc.),
    #   (d) a `<V> = sum(<W>, <atom>)` aggregate body item — vlog's
    #       engine-native SumAggregateSpec binds V at post-join time.
    # Anything not covered would leave a head var unbound — drop the rule.
    _SUM_AGG_BIND_RE = re.compile(
        r"^\s*([A-Z_][A-Za-z0-9_]*)\s*=\s*sum\s*\("
    )
    bound_by_body: Set[str] = set()
    for be in rule.body:
        if be.is_atom and not be.is_negated:
            for arg in be.args:
                if _is_variable(arg):
                    bound_by_body.add(arg)
            continue
        if not be.is_atom:
            raw = be.raw.strip()
            # Positive `(X = c)` acts as a binder when X has no other body
            # source — vlog's EQCMP evaluator now binds an unbound var to the
            # literal (mirrors Souffle BinaryConstraint's bind-on-unbound
            # semantics). Negated `~((X = c))` never binds and is skipped.
            m = _EQ_CONSTRAINT_RE.match(raw)
            if m is not None:
                negated, var, _ = m.group(1), m.group(2), m.group(3)
                if not negated:
                    bound_by_body.add(var)
            m = _DECR_CONSTRAINT_RE.match(raw)
            if m is not None:
                bound_by_body.add(m.group(1))
            m = _BAND_CONSTRAINT_RE.match(raw)
            if m is not None:
                bound_by_body.add(m.group(1))
            msum = _SUM_AGG_BIND_RE.match(raw)
            if msum is not None:
                bound_by_body.add(msum.group(1))
    for raw_head_arg in rule.head_args:
        if not _is_variable(raw_head_arg):
            continue
        if raw_head_arg not in bound_by_body:
            return (None, [], "untranslatable")

    for body_elem in rule.body:
        if not body_elem.is_atom:
            raw = body_elem.raw.strip()
            # SUM aggregate: `V = sum(W, pred(args))`. The inner atom needs
            # the same F/I column lifting as a regular body atom of the
            # same predicate, and the fresh F_sum is appended to f_vars so
            # it flows into the head's conj(F0, ..., F_sum) function term
            # — that's how the per-group DP formula (set by
            # SemiNaiver::applySumAggregatesAndEmitHead) reaches the
            # derived head tuple's probability.
            #
            # The `~d_pred(I_sum)` dedup guard that a normal IDB body
            # atom gets is intentionally omitted here: vlog's engine
            # accepts only a single witness atom inside `sum(...)`, and
            # the aggregator's group-by naturally ignores tombstoned
            # witnesses because their F column references a Constant(FALSE)
            # in the formula graph. Any correctness gap if a tombstoned
            # tuple sneaks in with a non-FALSE F would show up as an
            # over-count in sum-emit's probability — flagged as a known
            # follow-up in project_sum_aggregate_native.md.
            msum = _SUM_AGG_BODY_RE.match(raw)
            if msum is not None:
                lhs_var = msum.group(1)
                value_var = msum.group(2)
                inner_text = msum.group(3).strip().rstrip(",").strip()
                atom_m = _ATOM_HEAD_RE.match(inner_text)
                if atom_m is not None:
                    inner_pred = atom_m.group(1)
                    inner_args_raw = atom_m.group(2)
                    # Split top-level commas respecting parens.
                    inner_args: List[str] = []
                    depth = 0
                    cur = []
                    for ch in inner_args_raw:
                        if ch == "(":
                            depth += 1
                            cur.append(ch)
                        elif ch == ")":
                            depth -= 1
                            cur.append(ch)
                        elif ch == "," and depth == 0:
                            inner_args.append("".join(cur).strip())
                            cur = []
                        else:
                            cur.append(ch)
                    if cur:
                        inner_args.append("".join(cur).strip())
                    # `_` → fresh WC var per occurrence.
                    wc_inner: List[str] = []
                    for a in inner_args:
                        if a == "_":
                            wc_inner.append(
                                f"WC_sum_{rule_index}_{len(wc_inner)}"
                            )
                        else:
                            wc_inner.append(a)
                    if inner_pred in edb:
                        fi = fresh_var("F", len(f_vars))
                        f_vars.append(fi)
                        new_args = wc_inner[:-1] + [fi] if wc_inner else [fi]
                        lifted_atom = f"{inner_pred}({render_args(new_args)})"
                    elif inner_pred in idb:
                        fi = fresh_var("F", len(f_vars))
                        f_vars.append(fi)
                        ii = fresh_var("I", len(f_vars) - 1)
                        new_args = [*wc_inner, fi, ii]
                        lifted_atom = f"{inner_pred}({render_args(new_args)})"
                    else:
                        # Unknown predicate — pass through unchanged. The
                        # engine will warn on arity mismatch if the atom is
                        # malformed; no point guessing the right shape.
                        lifted_atom = inner_text
                    new_body_parts.append(
                        f"{lhs_var} = sum({value_var}, {lifted_atom})"
                    )
                    continue
            # Convert remaining Souffle constraints (negations, decrement)
            # into vlog BuiltinConstraint surface syntax. `~((X = c))` →
            # `X != c`, `(TIMES_NEW = (TIMES - 1))` → `TIMES_NEW = TIMES -
            # 1`. vlog's `tryParseBuiltinConstraint` lands these in
            # `Rule::builtins` and the post-join filter in
            # `SemiNaiver::applyBuiltinsAndEmitHead` evaluates them per
            # tuple — including for TcP `conj(F0,...,Fn)` heads via
            # ExistentialRuleProcessor + chaseMgmt.
            converted = _constraint_to_vlog_text(raw)
            if converted is not None:
                new_body_parts.append(converted)
                continue
            # Any other non-atom body expression (unlikely in practice) —
            # emit verbatim with !-to-~ translation preserved.
            expr = body_elem.raw.replace("\\+", "~")
            expr = re.sub(r"!(?=\s*[\w(])", "~", expr)
            new_body_parts.append(expr)
            continue
        pred = body_elem.pred
        args = list(body_elem.args)
        # Replace Souffle wildcards `_` with fresh variables per occurrence.
        # vlog's parser treats `_` as the LITERAL STRING "_" (dict-encoded
        # constant), not as a don't-care — so `pred(EA, _, F)` would only
        # match rows where col 1 literally equals the symbol "_", which is
        # almost never true. Replace each `_` with a fresh `WC<i>` var so
        # the join proceeds unconstrained at that position. Numbered per-rule
        # (via `len(f_vars)` + counter) to avoid collisions within the rule.
        wc_args = []
        for a in args:
            if a.strip() == "_":
                wc_args.append(f"WC_{rule_index}_{len(wc_args)}_{len(new_body_parts)}")
            else:
                wc_args.append(a)
        args = wc_args
        neg = body_elem.is_negated
        if pred in edb:
            # Probabilistic EDB — adds F column only. The source esrc_X csv
            # already carries `(args..., FID)`, so its arity here is args + 1.
            fi = fresh_var("F", len(f_vars))
            f_vars.append(fi)
            # EDB body atom already has args + FID in the rules file:
            # e.g. esrc_ISEMPTY(V0,V1,V2,FID). We drop the user's FID name and
            # re-bind to our fresh Fi so the conj carries Fi.
            if args and args[-1] == "FID":
                new_args = args[:-1] + [fi]
            else:
                # Defensive: assume last arg is the formula-id column.
                new_args = args[:-1] + [fi] if args else [fi]
            prefix = "~" if neg else ""
            new_body_parts.append(f"{prefix}{pred}({render_args(new_args)})")
            continue
        if pred in idb:
            if neg:
                # NAF on live IDB. Emitting the raw `~pred(args, F, I),
                # ~d_pred(I)` form crashes vlog's left-join processor with
                # a SIGSEGV at InterTableJoinProcessor::processResults
                # because the fresh F/I vars aren't bound by a preceding
                # positive literal. Instead, route through an auxiliary
                # `has_pred(keys...)` witness that the caller materialises
                # once per predicate listed in `naf_idb_used`.
                if naf_idb_used is not None:
                    naf_idb_used.add(pred)
                new_body_parts.append(f"~has_{pred}({render_args(args)})")
                continue
            # Live-form IDB reference — adds F column + I column + ~d_<pred>(I) guard.
            fi = fresh_var("F", len(f_vars))
            f_vars.append(fi)
            ii = fresh_var("I", len(f_vars) - 1)
            new_body_parts.append(f"{pred}({render_args([*args, fi, ii])})")
            new_body_parts.append(f"~d_{pred}({ii})")
            continue
        # Unknown predicate (shouldn't normally happen) — pass through.
        prefix = "~" if neg else ""
        new_body_parts.append(f"{prefix}{pred}({render_args(args)})")

    # Lift head constants into body atoms (see docstring). For each non-
    # variable token in the head args, mint `esrc_ctx_<const>(V)` with a
    # fresh V and replace the head position with V. Must happen *after* all
    # body processing so the new body atom appears before the first
    # universal var in the materialised body — vlog needs the var bound
    # before any later atom can reference it.
    # Head args used verbatim — positive `(X = C)` no longer substitutes X→C
    # in the head; vlog's EQCMP filter post-join keeps only rows where the
    # body-bound X equals C, which has the same semantic effect.
    subbed_head_args = list(rule.head_args)
    lifted_head_args: List[str] = []
    lift_prefix_body: List[str] = []

    # Recognise binary arithmetic head args like `End - EA`. vlog's parser
    # now lifts these into a body builtin (`__head_T<n> = End - EA`) at
    # parseRule time — we just need to pass the expression through
    # unchanged. The constant-lifting path below would otherwise wrap the
    # whole expression as a string in a synthetic `esrc_ctx_<...>` EDB,
    # producing a literal-string Size column that breaks downstream rules.
    _HEAD_ARITH_RE = re.compile(
        r"^\s*[A-Z_][A-Za-z0-9_]*\s*[+\-*/%]\s*[A-Z_][A-Za-z0-9_]*\s*$"
    )

    for tok in subbed_head_args:
        if _is_variable(tok):
            lifted_head_args.append(tok)
            continue
        if _HEAD_ARITH_RE.match(tok):
            # Arithmetic expression — pass through verbatim; vlog's
            # head-arith lifting will handle it.
            lifted_head_args.append(tok)
            continue
        # Constant — lift it.
        const_token = tok
        safe_const = re.sub(r"[^A-Za-z0-9_]", "_", const_token)
        if safe_const and safe_const[0].isdigit():
            safe_const = "n" + safe_const
        ctx_pred = f"esrc_ctx_{safe_const}"
        fresh = f"CTX_{safe_const.upper()}_{len(lift_prefix_body)}"
        lift_prefix_body.append(f"{ctx_pred}({fresh})")
        lifted_head_args.append(fresh)
        if head_const_consts is not None:
            head_const_consts.add(const_token)
    if lift_prefix_body:
        new_body_parts = lift_prefix_body + new_body_parts

    # Head of the t_ rule carries the original head args, then every Fi, then
    # conj(F1,...,Fk) as a function term. The vProbLog requirement at
    # extresultjoinproc.cpp:42 is that every var inside conj() also appear as
    # a top-level head arg — which is what we just did.
    head_args_all = [*lifted_head_args, *f_vars]
    if f_vars:
        if len(f_vars) == 1:
            # conj([F]) collapses to F — match vProbLog scenario smokers-20-40-2
            # which emits `t_1_smokes(X,F1) :- stress(X,F1)` (no conj() when
            # there's only one body formula). But we emit conj(F1) anyway: our
            # patched addRow handles a single-arg conj (returns the arg), and
            # the rule probability (if any) still gets conjoined as a fresh
            # per-grounding variable.
            head_args_all.append(f"conj({f_vars[0]})")
        else:
            head_args_all.append(f"conj({', '.join(f_vars)})")
    # If no probabilistic body atoms (pure constraints) we still need SOME
    # trivial formula. Emit conj() with a dummy `true` placeholder — not
    # expected in practice for our benchmark.
    elif not f_vars:
        head_args_all.append("conj()")

    head_text = f"t_{rule_index}_{rule.head_pred}({render_args(head_args_all)})"
    if rule.probability is not None and rule.probability < 1.0:
        head_text = f"{rule.probability}::{head_text}"
    body_text = ", ".join(new_body_parts)
    return f"{head_text} :- {body_text}.", f_vars, ""


def build_dedup_block(pred: str, arity: int, recursive: bool = False) -> List[str]:
    """Emit the dedup rules for an IDB predicate.

    Returns a list of 5 rule strings, indexed:
        [0] UNCONDITIONAL promotion (goes into secondphaseEdb — no self-negation)
        [1] CONDITIONAL first-time emission (goes into secondphaseIdb)
        [2] tt_ merge carrier (goes into secondphaseIdb)
        [3] re-emit after merge (goes into secondphaseIdb)
        [4] tombstone (goes into secondphaseIdb)

    The split matches vProbLog's `scenarios/smokers-20-40-2/rules` convention:
    secondphaseEdb unconditionally copies agg_ → live X once the EDB-bridge
    t_ rules are done. Using the negated form in secondphaseEdb causes
    self-negation over the same predicate being defined, which vlog's
    semi-naive treats as unstratified and consequently does not fire the
    downstream firstphaseRecIdb rules that depend on X as a body atom.

    The `recursive` flag is currently unused: a transform-side attempt to
    bypass the tt_/equiv/dis chain on recursive IDBs turned out to be a
    dead end — see `_compute_recursive_idb_set` and the rationale logged
    in transform_metadata.json. The flag is preserved as a hook in case a
    future revision wants to try a different dedup skeleton shape.
    """
    xs = [f"X{i}" for i in range(arity)]
    xs_text = render_args(xs)
    return [
        # [0] secondphaseEdb: unconditional promotion (no self-negation)
        f"{pred}({xs_text}, F, I) :- agg_{pred}({xs_text}, F, I).",
        # [1] secondphaseIdb: first-time emission guarded by ~X(...)
        f"{pred}({xs_text}, F, I) :- agg_{pred}({xs_text}, F, I), ~{pred}({xs_text}, F2, I2).",
        # [2] secondphaseIdb: tt_ merge carrier (triggers when equiv)
        f"tt_{pred}({xs_text}, F1, F2, I1, I2, dis(F1, F2)) :- "
        f"agg_{pred}({xs_text}, F1, I1), "
        f"{pred}({xs_text}, F2, I2), ~d_{pred}(I2), "
        f"equiv(F1, F2).",
        # [3] re-emit after merge
        f"{pred}({xs_text}, D, I1) :- tt_{pred}({xs_text}, F1, F2, I1, I2, D).",
        # [4] tombstone
        f"d_{pred}(I2) :- tt_{pred}({xs_text}, F1, F2, I1, I2, D).",
    ]


def build_req_rule(pred: str, arity: int, recursive: bool = False) -> str:
    xs = [f"X{i}" for i in range(arity)]
    xs_text = render_args(xs)
    return (
        f"req_{pred}({xs_text}, F) :- "
        f"{pred}({xs_text}, F, I), ~d_{pred}(I)."
    )


def _compute_recursive_idb_set(rules: Sequence[Rule]) -> Set[str]:
    """An IDB predicate is 'recursive' if some rule defining it references
    itself (directly) in the body. Transitive-closure, symmetric-closure,
    and chain-recursion patterns all match. The flag drives the
    build_dedup_block / build_req_rule simplification for predicates where
    the tt_/equiv/dis dedup loop would non-terminate."""
    recursive: Set[str] = set()
    for r in rules:
        for be in r.body:
            if be.is_atom and be.pred == r.head_pred:
                recursive.add(r.head_pred)
                break
    return recursive


def infer_predicate_arity(rules: Sequence[Rule], pred: str) -> int:
    """Arity of an IDB predicate = arity at which it appears in any head."""
    for r in rules:
        if r.head_pred == pred:
            return len(r.head_args)
    # Not a head — look in body.
    for r in rules:
        for b in r.body:
            if b.is_atom and b.pred == pred:
                # Body arity is data cols (no F/I yet since we haven't transformed).
                return len(b.args)
    return 0


def transform_case(source_case: Path, output_case: Path) -> TransformResult:
    src_rules_path = source_case / "rules"
    src_edb_path = source_case / "edb.conf"
    src_mappings = source_case / "mappings.csv"
    if not src_rules_path.is_file():
        raise FileNotFoundError(f"missing rules: {src_rules_path}")

    rules, declared_outputs = parse_rules_file(src_rules_path)
    edb_names = parse_edb_conf(src_edb_path)
    edb_set, idb_set = classify_predicates(rules, edb_names)

    # Copy the EDB data directory FIRST (so any split CSVs we write later
    # aren't overwritten by the verbatim copy).
    output_case.mkdir(parents=True, exist_ok=True)
    src_data = source_case / "data"
    if src_data.is_dir():
        dst_data = output_case / "data"
        if dst_data.exists():
            shutil.rmtree(dst_data)
        shutil.copytree(src_data, dst_data)

    # All former preprocessing hacks (_unroll_arithmetic for band/decr,
    # _split_edb_on_neq for VAR != CONST, _solve_eq_constraints for (X=c)
    # substitution) are intentionally removed. vlog now parses each of these
    # patterns natively: the `band` keyword is recognised by
    # tryParseBuiltinConstraint in concepts.cpp, negated (X != c) /
    # arithmetic decrement / positive (X = c) all reach the engine as real
    # BuiltinConstraint items and evaluate in applyBuiltinsAndEmitHead. The
    # Python transformer's job is now just the Souffle → TcP-native
    # lowering (t_/agg_/tt_/d_/req_ skeleton); semantics live in the engine.
    extra_edb: List[Dict[str, object]] = []

    # Partition rules:
    #   - EDB-bridge: body has one atom in edb_set (pattern `X(V0,...) :- esrc_X(V0,...,FID).`)
    #   - Final-anchor: head == body atom AND nothing else (pattern `X(V0) :- X(V0).`)
    #   - Regular IDB rule: everything else
    bridge_rules: List[Rule] = []
    anchor_rules: List[Rule] = []
    idb_rules: List[Rule] = []
    for r in rules:
        is_bridge = (
            len(r.body) == 1
            and r.body[0].is_atom
            and r.body[0].pred in edb_set
            and not r.body[0].is_negated
        )
        is_anchor = (
            len(r.body) == 1
            and r.body[0].is_atom
            and r.body[0].pred == r.head_pred
            and r.body[0].args == r.head_args
        )
        if is_bridge:
            bridge_rules.append(r)
        elif is_anchor:
            anchor_rules.append(r)
        else:
            idb_rules.append(r)

    # Gather query predicates — ones that appear as final-anchor heads, plus
    # any .output directives from the source.
    query_preds = {r.head_pred for r in anchor_rules} | set(declared_outputs)

    # Build predicate arity table (for dedup/req emission).
    idb_arity: Dict[str, int] = {}
    for pred in idb_set:
        idb_arity[pred] = infer_predicate_arity(rules, pred)

    # ---------------- emit ----------------

    out_lines: List[str] = []

    # --- firstphaseEdb: EDB → t_1_<pred> bridges ---
    out_lines.append("// firstphaseEdb")
    next_rule_id = 1
    dropped_unsat = 0
    dropped_untranslatable = 0
    naf_idb_used: Set[str] = set()
    head_const_consts: Set[str] = set()
    for r in bridge_rules:
        rule_text, _, reason = build_t_rule(r, next_rule_id, edb_set, idb_set, naf_idb_used, head_const_consts)
        if rule_text is None:
            if reason == "untranslatable":
                dropped_untranslatable += 1
            else:
                dropped_unsat += 1
            continue
        out_lines.append(rule_text)
        next_rule_id += 1

    # --- secondphaseEdb: unconditional agg_ → live IDB promotion ---
    out_lines.append("")
    out_lines.append("// secondphaseEdb")
    for pred in sorted(idb_set):
        arity = idb_arity.get(pred, 0)
        block = build_dedup_block(pred, arity)
        out_lines.append(block[0])  # unconditional `X(...) :- agg_X(...).`

    # --- firstphaseRecIdb: user-written IDB rules in t_ form ---
    out_lines.append("")
    out_lines.append("// firstphaseRecIdb")
    for r in idb_rules:
        rule_text, _, reason = build_t_rule(r, next_rule_id, edb_set, idb_set, naf_idb_used, head_const_consts)
        if rule_text is None:
            if reason == "untranslatable":
                dropped_untranslatable += 1
            else:
                dropped_unsat += 1
            continue
        out_lines.append(rule_text)
        next_rule_id += 1

    # NAF-witness rules: one `has_<pred>(keys...) :- <pred>(keys..., F, I),
    # ~d_<pred>(I).` per IDB pred that appears under NAF in any rule above.
    # Emitted in firstphaseRecIdb so the witness is re-derived as the
    # underlying IDB grows.
    if naf_idb_used:
        out_lines.append("")
        out_lines.append("// NAF witnesses (for ~has_<pred>(keys...) rewrites)")
        for pred in sorted(naf_idb_used):
            arity = idb_arity.get(pred, 0)
            key_vars = [f"X{i}" for i in range(arity)]
            out_lines.append(
                f"has_{pred}({', '.join(key_vars)}) :- "
                f"{pred}({', '.join([*key_vars, 'F', 'I'])}), ~d_{pred}(I)."
            )

    # --- secondphaseIdb: first-time-emission guard + merge / tombstone machinery ---
    out_lines.append("")
    out_lines.append("// secondphaseIdb")
    for pred in sorted(idb_set):
        arity = idb_arity.get(pred, 0)
        block = build_dedup_block(pred, arity)
        # block[0] already emitted in secondphaseEdb; emit [1..4] here:
        # conditional first-time, tt_ merge carrier, re-emit, tombstone.
        out_lines.extend(block[1:])

    # --- final: req_<pred> for queries ---
    out_lines.append("")
    out_lines.append("// final")
    for pred in sorted(query_preds):
        arity = idb_arity.get(pred)
        if arity is None:
            continue
        out_lines.append(build_req_rule(pred, arity))

    rules_text = "\n".join(out_lines) + "\n"

    # edb.conf: start from the source edb.conf, then append entries for
    # every freshly materialised split EDB.
    edb_text = src_edb_path.read_text(encoding="utf-8") if src_edb_path.is_file() else ""

    def _next_edb_idx() -> int:
        indices = [
            int(m.group(1)) for m in re.finditer(r"^EDB(\d+)_predname=", edb_text, re.M)
        ]
        return (max(indices) + 1) if indices else 0

    if extra_edb:
        next_idx = _next_edb_idx()
        extra_lines: List[str] = []
        if edb_text and not edb_text.endswith("\n"):
            extra_lines.append("")
        for desc in extra_edb:
            name = desc["name"]
            extra_lines.append(f"EDB{next_idx}_predname={name}")
            extra_lines.append(f"EDB{next_idx}_type=INMEMORY")
            extra_lines.append(f"EDB{next_idx}_param0=data")
            extra_lines.append(f"EDB{next_idx}_param1={name}")
            next_idx += 1
        edb_text = edb_text + ("\n" if edb_text and not edb_text.endswith("\n") else "") \
            + "\n".join(extra_lines)
        if not edb_text.endswith("\n"):
            edb_text += "\n"

    # For every head constant lifted into a body atom (see build_t_rule
    # docstring), declare an INMEMORY EDB `esrc_ctx_<const>` and write a
    # single-row CSV `data/esrc_ctx_<const>.csv` containing the constant.
    if head_const_consts:
        for const_token in sorted(head_const_consts):
            safe_const = re.sub(r"[^A-Za-z0-9_]", "_", const_token)
            if safe_const and safe_const[0].isdigit():
                safe_const = "n" + safe_const
            ctx_pred = f"esrc_ctx_{safe_const}"
            if re.search(rf"^EDB\d+_predname={re.escape(ctx_pred)}\s*$",
                         edb_text, re.M):
                continue
            next_idx = _next_edb_idx()
            lines = [
                f"EDB{next_idx}_predname={ctx_pred}",
                f"EDB{next_idx}_type=INMEMORY",
                f"EDB{next_idx}_param0=data",
                f"EDB{next_idx}_param1={ctx_pred}",
            ]
            if edb_text and not edb_text.endswith("\n"):
                edb_text += "\n"
            edb_text = edb_text + "\n".join(lines) + "\n"
            csv_path = output_case / "data" / f"{ctx_pred}.csv"
            csv_path.parent.mkdir(parents=True, exist_ok=True)
            if not csv_path.is_file():
                csv_path.write_text(f"{const_token}\n", encoding="utf-8")

    # Ensure `equiv` is declared as an EDB with a single placeholder row,
    # mirroring what every reference vProbLog scenario (smokers, genes,
    # LUBM) does. The secondphaseIdb tt_ merge rules carry
    # `equiv(F1, F2)` in their body; if we don't declare it, vlog treats
    # it as an undefined IDB which trips up stratification / bodyChangedSince
    # analysis and prevents later firstphaseRecIdb rules from ever firing
    # on recursive taint-style programs. One trivial `(x, x)` row is enough
    # — the reference scenarios all ship with exactly that content.
    if not re.search(r"^EDB\d+_predname=equiv\s*$", edb_text, re.M):
        next_idx = _next_edb_idx()
        equiv_lines = [
            f"EDB{next_idx}_predname=equiv",
            f"EDB{next_idx}_type=INMEMORY",
            f"EDB{next_idx}_param0=data",
            f"EDB{next_idx}_param1=equiv",
        ]
        if edb_text and not edb_text.endswith("\n"):
            edb_text += "\n"
        edb_text = edb_text + "\n".join(equiv_lines) + "\n"
        equiv_csv = output_case / "data" / "equiv.csv"
        equiv_csv.parent.mkdir(parents=True, exist_ok=True)
        if not equiv_csv.is_file():
            # vlog's `equiv` predicate has a special builtin handler in
            # joinprocessor.cpp:681 — it ignores table contents and instead
            # calls `compareFormulas` for every intermediate row. A non-empty
            # placeholder like `x,x` triggers that handler on every iteration
            # of the recursive `tt_X(...) :- ..., equiv(F1, F2).` rule, which
            # explodes both runtime and memory on cipt-cg / pt-obj (vlog OOM'd
            # at ~7 GB on and-roc). Leaving equiv EMPTY keeps the EDB declared
            # (vlog's stratification still recognises the predicate) while
            # making `tt_X` join with 0 rows — matching the legacy
            # taint_appendix runs that produced correct tuple sets and per-
            # tuple probabilities consistent with souffle's facts.prob.
            equiv_csv.write_text("", encoding="utf-8")

    # Write outputs (data/ was already copied at the top of this function).
    (output_case / "rules").write_text(rules_text, encoding="utf-8")
    (output_case / "edb.conf").write_text(edb_text, encoding="utf-8")
    if src_mappings.is_file():
        shutil.copyfile(src_mappings, output_case / "mappings.csv")

    metadata = {
        "case": source_case.name,
        "edb_predicates": sorted(edb_set),
        "idb_predicates": sorted(idb_set),
        "query_predicates": sorted(query_preds),
        "idb_arity": idb_arity,
        "bridge_rules": len(bridge_rules),
        "idb_rules": len(idb_rules),
        "anchor_rules_dropped": len(anchor_rules),
        "unsat_rules_dropped": dropped_unsat,
        "untranslatable_rules_dropped": dropped_untranslatable,
        "edb_splits": extra_edb,
        "note": (
            "Requires the patched vlog binary (supports p:: on rule heads via "
            "fresh per-grounding variables) and an `equiv` external function "
            "registered in the engine. Pure vanilla vProbLog still can't run "
            "this because (a) it rejects p:: on rule heads — Tsamoura et al. "
            "§2 restricts probabilities to facts — and (b) our benchmark's "
            "rule probabilities would need pre-grounding via Souffle to be "
            "desugared into per-grounding aux probabilistic facts."
        ),
    }
    (output_case / "transform_metadata.json").write_text(
        json.dumps(metadata, indent=2), encoding="utf-8"
    )

    return TransformResult(
        rules_text=rules_text, edb_conf_text=edb_text, metadata=metadata
    )


# ---------------- CLI ----------------

def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Transform bridge-style vProbLog cases to Tsamoura et al. t_S / agg_ / tt_ / d_ / req_ native form."
    )
    p.add_argument("--source", type=Path, required=True,
                   help="Input root (e.g. out/side_channel_vproblog_all or out/taint_vproblog_all).")
    p.add_argument("--output", type=Path, required=True,
                   help="Output root (e.g. out/side_channel_vproblog_native).")
    p.add_argument("--case", action="append",
                   help="Specific case subdir name(s); repeatable. Default: all subdirs.")
    p.add_argument("--clean", action="store_true",
                   help="Remove the output root before writing.")
    p.add_argument("--reify-rule-probs", action="store_true",
                   help=("Reify p:: rule-head probabilities as auxiliary probabilistic "
                         "facts. Requires a Souffle pre-grounding pass; NOT implemented."))
    return p.parse_args()


def main() -> int:
    args = parse_args()
    if args.reify_rule_probs:
        print("ERROR: --reify-rule-probs not yet implemented. Skipping.", file=sys.stderr)
        print("  Use the default mode, which relies on the patched vlog's "
              "per-grounding fresh-variable minting to carry p:: rule probabilities.",
              file=sys.stderr)
        return 2

    source_root = args.source.resolve()
    output_root = args.output.resolve()
    if not source_root.is_dir():
        print(f"ERROR: source not found: {source_root}", file=sys.stderr)
        return 2

    if args.clean and output_root.exists():
        shutil.rmtree(output_root)
    output_root.mkdir(parents=True, exist_ok=True)

    case_names: List[str]
    if args.case:
        case_names = list(args.case)
    else:
        case_names = sorted(p.name for p in source_root.iterdir() if p.is_dir())

    summary = []
    ok = 0
    for i, name in enumerate(case_names, 1):
        source_case = source_root / name
        output_case = output_root / name
        if not source_case.is_dir():
            print(f"[transform] [{i}/{len(case_names)}] {name}  SKIP (not a dir)")
            continue
        print(f"[transform] [{i}/{len(case_names)}] {name}")
        try:
            res = transform_case(source_case, output_case)
        except Exception as exc:  # noqa: BLE001
            print(f"  FAILED: {exc}")
            summary.append({"case": name, "status": "failed", "error": str(exc)})
            continue
        md = res.metadata
        print(
            f"  edb={len(md['edb_predicates'])} idb={len(md['idb_predicates'])} "
            f"bridges={md['bridge_rules']} idb_rules={md['idb_rules']} "
            f"unsat_dropped={md.get('unsat_rules_dropped', 0)} "
            f"untranslatable_dropped={md.get('untranslatable_rules_dropped', 0)}"
        )
        summary.append({"case": name, "status": "ok", **{k: v for k, v in md.items()
                                                         if k in ("bridge_rules",
                                                                  "idb_rules",
                                                                  "anchor_rules_dropped")}})
        ok += 1

    (output_root / "transform_summary.json").write_text(
        json.dumps({"source": str(source_root), "cases": summary}, indent=2),
        encoding="utf-8",
    )
    print(f"[transform] done: {ok}/{len(case_names)} cases transformed")
    return 0 if ok == len(case_names) else 1


if __name__ == "__main__":
    raise SystemExit(main())
