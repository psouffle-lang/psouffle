# ---------------- parsing helpers ----------------

PROB_PREFIX_RE = re.compile(
    r"^\s*([+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?)::\s*(.+)$"
)
PHASE_COMMENT_RE = re.compile(r"^\s*//\s*([A-Za-z_][A-Za-z0-9_]*)\s*$")
HEAD_PRED_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\s*(?:\((.*)\))?\s*$")
ATOM_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\s*\((.*)\)\s*$")


def split_top_level(text: str, sep: str = ",") -> List[str]:
    parts: List[str] = []
    depth = 0
    cur: List[str] = []
    for ch in text:
        if ch == "(":
            depth += 1
            cur.append(ch)
        elif ch == ")":
            if depth > 0:
                depth -= 1
            cur.append(ch)
        elif ch == sep and depth == 0:
            p = "".join(cur).strip()
            if p:
                parts.append(p)
            cur = []
        else:
            cur.append(ch)
    tail = "".join(cur).strip()
    if tail:
        parts.append(tail)
    return parts


@dataclass
class BodyElement:
    """A parsed rule-body element — either a predicate atom or a raw constraint."""
    raw: str
    is_atom: bool
    is_negated: bool = False
    pred: Optional[str] = None
    args: List[str] = field(default_factory=list)

    @classmethod
    def parse(cls, text: str) -> "BodyElement":
        t = text.strip()
        is_neg = False
        # Strip Souffle `!` or vProbLog `~` negation prefix.
        while t.startswith("~") or t.startswith("!") or t.startswith("\\+"):
            if t.startswith("\\+"):
                t = t[2:].strip()
            else:
                t = t[1:].strip()
            is_neg = True
        # Constraints like `(X = 0)` or `(TMP = (X band Y))` — match them as
        # parenthesised expressions with no top-level pred name.
        if t.startswith("(") and t.endswith(")"):
            return cls(raw=text.strip(), is_atom=False, is_negated=is_neg)
        m = ATOM_RE.match(t)
        if m is None:
            return cls(raw=text.strip(), is_atom=False, is_negated=is_neg)
        return cls(
            raw=text.strip(),
            is_atom=True,
            is_negated=is_neg,
            pred=m.group(1),
            args=[a.strip() for a in split_top_level(m.group(2))],
        )


@dataclass
class Rule:
    probability: Optional[float]  # None => deterministic (no p:: prefix)
    head_pred: str
    head_args: List[str]
    body: List[BodyElement]
    source_line: int


def parse_rules_file(path: Path) -> Tuple[List[Rule], List[str]]:
    rules: List[Rule] = []
    output_predicates: List[str] = []
    with path.open(encoding="utf-8") as f:
        for idx, raw in enumerate(f):
            line = raw.rstrip("\n")
            stripped = line.strip()
            if not stripped:
                continue
            if stripped.startswith("//"):
                continue
            # Support .output declarations if present (not in our case generator).
            if stripped.startswith(".output"):
                tok = stripped.split()
                if len(tok) >= 2:
                    output_predicates.append(tok[1].rstrip("(."))
                continue
            if stripped.startswith("."):
                continue
            if ":-" not in stripped:
                continue
            head_part, body_part = stripped.split(":-", 1)
            head_part = head_part.strip()
            body_part = body_part.strip()
            if body_part.endswith("."):
                body_part = body_part[:-1].rstrip()
            prob: Optional[float] = None
            m_prob = PROB_PREFIX_RE.match(head_part)
            if m_prob is not None:
                prob = float(m_prob.group(1))
                head_part = m_prob.group(2).strip()
            head_match = ATOM_RE.match(head_part)
            if head_match is None:
                # head with no args
                simple = HEAD_PRED_RE.match(head_part)
                if simple is None:
                    continue
                head_pred = simple.group(1)
                head_args: List[str] = []
            else:
                head_pred = head_match.group(1)
                head_args = [a.strip() for a in split_top_level(head_match.group(2))]
            body_elems = [BodyElement.parse(p) for p in split_top_level(body_part)]
            rules.append(Rule(
                probability=prob,
                head_pred=head_pred,
                head_args=head_args,
                body=body_elems,
                source_line=idx + 1,
            ))
    return rules, output_predicates


def parse_edb_conf(path: Path) -> List[str]:
    """Return the list of EDB predicate names from an edb.conf file."""
    names: List[str] = []
    if not path.is_file():
        return names
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line.startswith("EDB") and "_predname=" in line:
            names.append(line.split("_predname=", 1)[1].strip())
    return names


