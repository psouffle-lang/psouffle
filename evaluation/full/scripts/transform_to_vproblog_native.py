#!/usr/bin/env python3
"""Transform a bridge-style vProbLog case folder (as produced by
generate_vproblog_side_channel.py / generate_vproblog_taint.py) into the
native t_S / agg_ / tt_ / d_ / req_ form described in Tsamoura, Gutierrez-
Basulto, Kimmig ("Beyond the Grounding Bottleneck", AAAI 2020; arXiv
1911.07750), §3 "Semi-naive Evaluation for TcP".

Paper → vProbLog surface-syntax rename:
    lambda(atom, formula, id)        ↔  atom(args..., F, I)          (live IDB)
    d(head, conj([F1,...,Fn]))       ↔  t_<N>_<head>(args..., F1,...,Fn, conj(F1,...,Fn))
    beta(head, disj(L))              ↔  agg_<head>(args..., F, I)    (vlog auto-generates)
    aux(head, disj([D,F]), I)        ↔  tt_<head>(args..., F1, F2, I1, I2, dis(F1,F2))
    outdated(I)                      ↔  d_<head>(I)
    equivalent(F1, F2)               ↔  equiv(F1, F2)   (external SDD function)
    final projection                 ↔  req_<head>(args..., F) :- <head>(args..., F, I), ~d_<head>(I).

Phase structure (per scenarios/smokers-20-40-2/rules):
    //firstphaseEdb       bridge EDB (esrc_X(args, F)) into t_1_X(args, F)
    //secondphaseEdb      auto-promotion of agg_X to live X(args, F, I)
    //firstphaseRecIdb    the user's original IDB rules, each rewritten into t_<N>_<head>
    //secondphaseIdb      per-head dedup machinery (tt_, first-time, merge, d_)
    //final               req_<head> for every .output predicate

ProbLog distribution semantics strictly allows probabilities only on facts,
not rules (Tsamoura et al. §2). Our source benchmark violates this by putting
p:: on rule heads. Two handling options:

  (a) "Patched-vlog" mode (default): keep `p::` on the emitted t_<N>_<head>
      rule. Our patched vlog's ChaseMgmt::Rows::addRow then mints a fresh
      per-grounding random variable with weight p and conjoins it into the
      `conj(...)` result. This yields correct per-grounding ProbLog semantics
      without needing to pre-enumerate groundings.

  (b) "Reified" mode (--reify-rule-probs): replaces `p::head :- body.` with a
      deterministic rule plus an extra probabilistic body atom `r_<N>(X̄, F)`
      whose EDB has to be pre-generated by a Souffle probe pass. NOT yet
      implemented — will error out with a todo message if requested.

Usage:
    python3 scripts/transform_to_vproblog_native.py \\
        --source out/side_channel_vproblog_all \\
        --output out/side_channel_vproblog_native \\
        --clean
"""

